// Vendors the three webfaces the desktop UI depends on, from the installed
// @fontsource packages into src-tauri/spike-ui/vendor/fonts/.
//
// WHY THIS EXISTS
//
// index.html used to pull EB Garamond, IBM Plex Sans and JetBrains Mono from
// fonts.googleapis.com with display=swap -- in a DESKTOP app, while every
// other third-party asset here (marked, xterm, the React runtime, the
// Tailwind preflight) was already vendored locally by a sibling of this
// script. Three consequences, all real:
//
//   1. Offline, or behind a firewall, all three faces silently fall back to
//      system fonts. The entire typographic system the design kit says
//      carries the product's tone just disappears -- and the app looks
//      different depending on the network, which is very literally "the UI is
//      inconsistent".
//   2. Even online, display=swap guarantees a visible reflow on every cold
//      start as the real faces arrive.
//   3. README.md claimed "the app never makes HTTP calls". It did, twice --
//      here and the updater endpoint.
//
// HOW IT WORKS
//
// Same shape as generate-vendored-marked.mjs: read from already-installed
// node_modules, write into vendor/. NO NETWORK AT BUILD TIME -- npm install
// is the only thing that ever fetches, and the versions are pinned in
// package-lock.json, so two machines produce byte-identical output.
//
// Two things this must get right that a marked-style copy would not:
//
//   - Font files are BINARY. generate-vendored-marked.mjs reads and writes
//     with 'utf-8', which would silently corrupt every .woff2. This uses
//     copyFileSync.
//   - @fontsource's own CSS points at `./files/...` relative to the package.
//     Rather than copy and rewrite it, this emits its own @font-face block,
//     which also lets us ship only the latin subset and only the weights the
//     app actually uses (11 faces, ~252 KB) instead of every weight and every
//     unicode range the packages carry.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(repoRoot, 'src-tauri', 'spike-ui', 'vendor', 'fonts');

/** Exactly the faces index.html used to request from Google Fonts -- no more,
 *  no less, so this is a like-for-like replacement rather than a redesign. */
const FACES = [
  { family: 'EB Garamond', pkg: 'eb-garamond', weight: 400, style: 'normal' },
  { family: 'EB Garamond', pkg: 'eb-garamond', weight: 500, style: 'normal' },
  { family: 'EB Garamond', pkg: 'eb-garamond', weight: 600, style: 'normal' },
  { family: 'EB Garamond', pkg: 'eb-garamond', weight: 400, style: 'italic' },
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', weight: 400, style: 'normal' },
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', weight: 500, style: 'normal' },
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', weight: 600, style: 'normal' },
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', weight: 700, style: 'normal' },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', weight: 400, style: 'normal' },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', weight: 500, style: 'normal' },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', weight: 600, style: 'normal' },
];

fs.mkdirSync(outDir, { recursive: true });

const blocks = [];
let totalBytes = 0;

for (const face of FACES) {
  const fileName = `${face.pkg}-latin-${face.weight}-${face.style}.woff2`;
  const src = path.join(repoRoot, 'node_modules', '@fontsource', face.pkg, 'files', fileName);
  if (!fs.existsSync(src)) {
    console.error(`Missing font file: ${src}`);
    console.error('Run `npm install` first -- this script only reads node_modules, it never fetches.');
    process.exit(1);
  }
  const dest = path.join(outDir, fileName);
  // copyFileSync, NOT readFileSync('utf-8') -- these are binary.
  fs.copyFileSync(src, dest);
  totalBytes += fs.statSync(dest).size;

  blocks.push(
    `@font-face {\n`
    + `  font-family: '${face.family}';\n`
    + `  font-style: ${face.style};\n`
    + `  font-weight: ${face.weight};\n`
    // `swap` is deliberate even locally: the file is on disk and resolves in
    // microseconds, so there is no flash to avoid, and `swap` keeps text
    // visible if a face is ever missing rather than hiding it.
    + `  font-display: swap;\n`
    + `  src: url('fonts/${fileName}') format('woff2');\n`
    + `}`,
  );
}

const header = `/* GENERATED by scripts/generate-vendored-fonts.mjs -- do not edit by hand.
 *
 * Replaces the Google Fonts <link> index.html used to carry. Vendored so the
 * desktop app renders identically offline, behind a firewall, and on a cold
 * start -- see that script's header for the full reasoning.
 *
 * Latin subset only, and only the ${FACES.length} weights the app actually uses.
 * Regenerated automatically by the prepare/prebuild/pretest npm hooks. */\n\n`;

fs.writeFileSync(path.join(outDir, '..', 'fonts.css'), header + blocks.join('\n\n') + '\n', 'utf-8');

console.log(
  `vendored ${FACES.length} font faces (${Math.round(totalBytes / 1024)} KB) -> `
  + `${path.relative(repoRoot, outDir)}`,
);
