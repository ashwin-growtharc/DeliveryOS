#!/usr/bin/env node
// Generates src/engine/preview/vendoredTailwindPreflight.generated.ts -- a
// plain string constant holding the exact contents of Tailwind's own
// `preflight.css` (its built-in browser-normalization stylesheet: removes
// default margins, resets box-sizing, strips default <button>/<input>
// chrome, etc.).
//
// Why this exists at all: Tailwind's `preflight` core plugin does NOT
// generate this CSS programmatically -- it reads its own package's
// `lib/css/preflight.css` off disk at RUNTIME via a plain `fs.readFileSync`
// (see node_modules/tailwindcss/lib/corePlugins.js, the `preflight`
// function). esbuild's bundler has no way to see that call coming (it's
// not an `import`/`require` of the file, just a computed path built from
// `__dirname` at runtime) -- confirmed by hand: running the real packaged
// sidecar produced `ENOENT: no such file or directory, open
// '...\build\css\preflight.css'`, since the packaged Node SEA has no
// node_modules (and therefore no tailwindcss package directory) anywhere
// near it at all. The exact same class of problem this project already
// hit twice before (esbuild's own native binary, then React's UMD-style
// runtime) -- and the same fix: read the ONE static file this needs, once,
// at build time, and ship its contents as a plain string constant instead
// of a runtime file path.
//
// compile.ts disables Tailwind's own `preflight` core plugin entirely
// (`corePlugins: { preflight: false }`, avoiding the runtime read that
// would otherwise throw) and prepends this constant to the generated
// utility CSS itself instead.
//
// Run this whenever the pinned `tailwindcss` version changes
// (package.json) -- preflight.css is static per-version, not derived from
// any project-specific content, so (unlike the utility CSS itself) it
// never needs regenerating per-component, only per-Tailwind-upgrade.

import * as fs from 'node:fs';
import * as path from 'node:path';
import * as url from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const repoRoot = path.join(here, '..');
const outFile = path.join(repoRoot, 'src', 'engine', 'preview', 'vendoredTailwindPreflight.generated.ts');

const require = createRequire(import.meta.url);
// Resolved via tailwindcss's own package.json, not a hardcoded
// "lib/css/preflight.css" path glued onto node_modules/tailwindcss --
// robust to tailwindcss ever changing its own internal directory layout
// (package.json's location is the one thing guaranteed stable).
const tailwindPkgDir = path.dirname(require.resolve('tailwindcss/package.json'));
const preflightPath = path.join(tailwindPkgDir, 'lib', 'css', 'preflight.css');

function main() {
  console.log(`Reading ${preflightPath}...`);
  const css = fs.readFileSync(preflightPath, 'utf-8');
  console.log(`Preflight CSS size: ${(css.length / 1024).toFixed(1)} KB`);

  const fileContents = `// AUTO-GENERATED by scripts/generate-vendored-tailwind-preflight.mjs --
// do not edit by hand. Regenerate with:
// node scripts/generate-vendored-tailwind-preflight.mjs
// (whenever the pinned tailwindcss version in package.json changes).
//
// The exact contents of tailwindcss's own lib/css/preflight.css,
// embedded as a plain string constant -- see this generation script's own
// header for why a runtime file read can't be used instead. Prepended to
// the utility CSS generateTailwindCss (compile.ts) produces at compile
// time, with Tailwind's own \`preflight\` core plugin disabled.
export const VENDORED_TAILWIND_PREFLIGHT_CSS = ${JSON.stringify(css)};
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, fileContents, 'utf-8');
  console.log(`Wrote ${outFile}`);
}

main();
