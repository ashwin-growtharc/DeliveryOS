#!/usr/bin/env node
// Generates src-tauri/spike-ui/vendor/docx-preview.js for the Document tab
// (viewer.js): docx-preview and its JSZip dependency bundled into one IIFE,
// then wrapped as a STRING on `window.DeliveryOSDocxBundle`.
//
// Why a string and not a runnable bundle like vendor/xterm.js: the Word page
// is rendered inside a sandboxed `srcdoc` iframe -- an opaque origin, the same
// isolation the markdown renderer uses -- and an opaque-origin frame cannot
// reliably load a sibling `<script src="vendor/...">` (the origin differs
// between `file://` in the browser tests and `tauri.localhost` in the app, and
// a strict CSP inside the frame has nothing to name). Inlining the bundle text
// into the frame's own `<script>` sidesteps the question entirely: the frame
// needs no network, no origin, and `npm run ui:fonts`'s "nothing but file://"
// check stays true.
//
// The only escaping a JS-in-JSON string needs to survive inside a `<script>`
// element is `</` -> `<\/`, which is a legal JSON escape, so the string is
// still `JSON.parse`-able and the parser never sees a premature `</script>`.
//
// Run this whenever the pinned docx-preview or jszip version changes. Wired as
// an npm "prepare"/"prebuild"/"pretypecheck"/"pretest" step alongside the other
// generators; CI's vendor drift check catches a stale output.
//
// Licences: docx-preview is Apache-2.0; JSZip is dual MIT / GPL-3.0-or-later
// and is used here under MIT.

import * as esbuild from 'esbuild';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const repoRoot = path.join(here, '..');
const vendorDir = path.join(repoRoot, 'src-tauri', 'spike-ui', 'vendor');
const outFile = path.join(vendorDir, 'docx-preview.js');

async function bundle() {
  // `renderAsync` is the one export the viewer calls. Everything else the
  // library exports rides along under `window.docx`, the same name its own
  // UMD build uses, so the frame's code reads like the library's docs.
  const shim = `
    import * as docx from 'docx-preview';
    window.docx = docx;
  `;
  const result = await esbuild.build({
    stdin: {
      contents: shim,
      resolveDir: repoRoot,
      loader: 'js',
      sourcefile: 'vendored-docx-preview-shim.js',
    },
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
  });
  await esbuild.stop();
  return result.outputFiles[0].text;
}

async function main() {
  console.log('Bundling docx-preview + jszip...');
  const js = await bundle();
  console.log(`  ${(js.length / 1024).toFixed(1)} KB`);

  const asString = JSON.stringify(js).replace(/<\//g, '<\\/');
  const out =
    '// Generated by scripts/generate-vendored-docx-preview.mjs -- do not edit.\n'
    + '// docx-preview + jszip as ONE string, for inlining into a sandboxed srcdoc\n'
    + '// iframe. See the generator for why a string rather than a runnable bundle.\n'
    + `window.DeliveryOSDocxBundle = ${asString};\n`;

  fs.mkdirSync(vendorDir, { recursive: true });
  fs.writeFileSync(outFile, out, 'utf-8');
  console.log(`Wrote ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
