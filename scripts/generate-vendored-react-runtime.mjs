#!/usr/bin/env node
// Generates src/engine/preview/vendoredReactRuntime.generated.ts -- a
// single browser-safe IIFE bundle of React + ReactDOM's client runtime,
// embedded as a plain string constant.
//
// Why this exists at all: DeliveryOS's UI-component preview pipeline
// (src/engine/preview/compile.ts) needs React/ReactDOM available inside a
// compiled preview's sandboxed iframe, but can't rely on Node's normal
// module resolution to find them at runtime -- the packaged sidecar ships
// as a Node SEA with no node_modules anywhere nearby (the exact same class
// of problem Phase A already solved for the native esbuild binary itself;
// see docs/phase-A-preview-packaging-spike.md). React 19 no longer ships a
// prebuilt UMD bundle (`node_modules/react/umd/` doesn't exist -- checked
// directly), so this script builds the equivalent itself: a tiny shim that
// imports React/ReactDOM's real ESM/CJS entry points and assigns them to a
// global, bundled via esbuild into one self-contained IIFE exactly like a
// real UMD build would be. The RESULT (a plain JS string) gets written to a
// normal local .ts file that src/engine/preview/compile.ts imports like any
// other module -- esbuild's own bundling of dist/sidecar.js -> sidecar.cjs
// then inlines that string directly into the packaged output, so nothing
// needs to be resolved from a filesystem at runtime at all.
//
// Run this whenever React/ReactDOM's pinned version changes (package.json).
// Must run before `tsc` -- wired as an npm "pregenerate" step; see
// package.json's "build" script.

import * as esbuild from 'esbuild';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const repoRoot = path.join(here, '..');
const outFile = path.join(repoRoot, 'src', 'engine', 'preview', 'vendoredReactRuntime.generated.ts');

const shim = `
  import React from 'react';
  import { createRoot } from 'react-dom/client';
  window.__DeliveryOSReactRuntime = { React, createRoot };
`;

async function main() {
  console.log('Bundling React + ReactDOM/client into a browser-safe IIFE...');
  const result = await esbuild.build({
    stdin: {
      contents: shim,
      resolveDir: repoRoot,
      loader: 'js',
      sourcefile: 'vendored-react-shim.js',
    },
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
  });
  await esbuild.stop();

  const bundledJs = result.outputFiles[0].text;
  console.log(`Bundled runtime size: ${bundledJs.length} bytes (${(bundledJs.length / 1024).toFixed(1)} KB)`);

  const fileContents = `// AUTO-GENERATED by scripts/generate-vendored-react-runtime.mjs -- do not
// edit by hand. Regenerate with: node scripts/generate-vendored-react-runtime.mjs
// (whenever the pinned react/react-dom version in package.json changes).
//
// A single browser-safe IIFE bundling React + ReactDOM's client runtime,
// assigning both to window.__DeliveryOSReactRuntime. Embedded as a preview's
// FIRST inline <script>, before the component's own bundle -- see
// src/engine/preview/compile.ts.
export const VENDORED_REACT_RUNTIME_JS = ${JSON.stringify(bundledJs)};
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, fileContents, 'utf-8');
  console.log(`Wrote ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
